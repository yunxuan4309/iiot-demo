package com.iiot.collector.core;

/**
 * 采集质量码 —— 工业数据里「值」和「这个值可不可信」是两件事。
 *
 * <p>电商系统里一个字段要么有值要么是 null；工业现场多出第三种状态：
 * <b>值是旧的</b>。设备掉线时如果补 0，下游会把「0℃」当真实温度（比没数据更危险），
 * 所以必须把「这条数据是哪一档」显式带给平台。
 */
public enum Quality {

    /** 本次采样是真的从设备读上来的。 */
    GOOD,

    /** 读失败，但手里有上一次的好值 —— 值是旧的，平台要显示"过期"而不是正常。 */
    STALE,

    /** 读失败且从未成功读过（或点位不存在）—— 连可用的旧值都没有。 */
    BAD
}
